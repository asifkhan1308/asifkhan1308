const dicts: Record<Lang, Partial<Record<StringKey, string>>> = { en, hi, hinglish };

const KEY = 'kaatchat.lang';
let lang: Lang = (() => {
  try {
    const v = localStorage.getItem(KEY);
    return v === 'hi' || v === 'hinglish' ? v : 'en';
  } catch {
    return 'en';
  }
})();
const listeners = new Set<() => void>();

export function setLang(l: Lang) {
  lang = l;
  try {
    localStorage.setItem(KEY, l);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = l === 'hi' ? 'hi' : 'en';
  for (const f of listeners) f();
}

export const getLang = () => lang;

/** A UI string in the current language; `{name}` placeholders are filled from `vars`. */
export function t(key: StringKey, vars?: Record<string, string | number>): string {
  const s = dicts[lang][key] ?? en[key];
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}

/** "1 file" / "3 files" in the current language. */
export const tFiles = (n: number) => t(n === 1 ? 'files.one' : 'files.many', { n });

/** Re-render on language change. */
export function useLang(): Lang {
  return useSyncExternalStore(
    (f) => {
      listeners.add(f);
      return () => listeners.delete(f);
    },
    () => lang,
  );
}
